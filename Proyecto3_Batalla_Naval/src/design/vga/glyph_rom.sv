                8'b01000010,
                8'b00000000
            };

            // I
            8'h49: pattern = {
                8'b00000000,
                8'b00111100,
                8'b00011000,
                8'b00011000,
                8'b00011000,
                8'b00011000,
                8'b00111100,
                8'b00000000
            };

            // J
            8'h4A: pattern = {
                8'b00000000,
                8'b00011110,
                8'b00000100,
                8'b00000100,
                8'b00000100,
                8'b01000100,
                8'b00111000,
                8'b00000000
            };

            // K
