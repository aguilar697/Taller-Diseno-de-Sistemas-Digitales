                8'b01001010,
                8'b00111100,
                8'b00000000
            };

            // R
            8'h52: pattern = {
                8'b00000000,
                8'b01111100,
                8'b01000010,
                8'b01000010,
                8'b01111100,
                8'b01001000,
                8'b01000110,
                8'b00000000
            };

            // S
            8'h53: pattern = {
                8'b00000000,
                8'b00111110,
                8'b01000000,
                8'b00111100,
                8'b00000010,
                8'b01000010,
                8'b00111100,
                8'b00000000
            };

            // T
            8'h54: pattern = {
                8'b00000000,
                8'b01111110,
                8'b00011000,
                8'b00011000,
                8'b00011000,
