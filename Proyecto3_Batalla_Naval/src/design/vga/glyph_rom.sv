            8'h31: pattern = {
                8'b00000000,
                8'b00011000,
                8'b00111000,
                8'b00011000,
                8'b00011000,
                8'b00011000,
                8'b00111100,
                8'b00000000
            };

            // 2
            8'h32: pattern = {
                8'b00000000,
                8'b00111100,
                8'b01000010,
                8'b00000100,
                8'b00011000,
                8'b00100000,
                8'b01111110,
                8'b00000000
            };

            // 3
            8'h33: pattern = {
                8'b00000000,
                8'b00111100,
                8'b01000010,
                8'b00001100,
                8'b00000010,
                8'b01000010,
                8'b00111100,
                8'b00000000
            };

            // 4
            8'h34: pattern = {
                8'b00000000,
                8'b00001100,
                8'b00010100,
                8'b00100100,
                8'b01000100,
                8'b01111110,
                8'b00000100,
                8'b00000000
            };

            // 5
            8'h35: pattern = {
                8'b00000000,
                8'b01111110,
                8'b01000000,
                8'b01111100,
                8'b00000010,
                8'b01000010,
                8'b00111100,
                8'b00000000
            };

            // 6
            8'h36: pattern = {
                8'b00000000,
                8'b00111100,
