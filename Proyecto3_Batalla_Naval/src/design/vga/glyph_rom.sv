            // Colon ':'
            8'h3A: pattern = {
                8'b00000000,
                8'b00000000,
                8'b00011000,
                8'b00000000,
                8'b00000000,
                8'b00011000,
                8'b00000000,
                8'b00000000
            };

            // Period '.'
            8'h2E: pattern = {
                8'b00000000,
                8'b00000000,
                8'b00000000,
                8'b00000000,
                8'b00000000,
                8'b00000000,
                8'b00011000,
                8'b00000000
            };

            // Unsupported ASCII codes are rendered as blank space.
            default: pattern = 64'b0;

        endcase
    end

    // -------------------------------------------------------------------------
    // Row selection
    // -------------------------------------------------------------------------
    // Selecciona una de las ocho filas del carácter actual.
    always_comb begin

        case (glyph_y_i)
            3'd0: row_bits = pattern[63:56];
            3'd1: row_bits = pattern[55:48];
            3'd2: row_bits = pattern[47:40];
            3'd3: row_bits = pattern[39:32];
            3'd4: row_bits = pattern[31:24];
            3'd5: row_bits = pattern[23:16];
            3'd6: row_bits = pattern[15:8];
            3'd7: row_bits = pattern[7:0];
            default: row_bits = 8'b0;
        endcase

    end

    // -------------------------------------------------------------------------
    // Column selection
    // -------------------------------------------------------------------------
    // glyph_x_i = 0 corresponde al bit izquierdo de la fila.
    assign glyph_bit_o = row_bits[7 - glyph_x_i];

endmodule