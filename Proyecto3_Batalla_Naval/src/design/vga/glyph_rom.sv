    input  logic [7:0] ascii_i,
    input  logic [2:0] glyph_x_i,
    input  logic [2:0] glyph_y_i,
    output logic       glyph_bit_o
);

    // -------------------------------------------------------------------------
    // Internal glyph representation
    // -------------------------------------------------------------------------
    // Cada carácter se representa mediante una matriz de 8 filas x 8 columnas.
    // El bit más significativo de cada fila corresponde al píxel izquierdo.
    //
    // pattern[63:56] -> fila 0
    // pattern[55:48] -> fila 1
    // ...
    // pattern[7:0]   -> fila 7
    logic [63:0] pattern;
    logic [7:0]  row_bits;

    // -------------------------------------------------------------------------
    // Glyph pattern lookup
    // -------------------------------------------------------------------------
    // Los códigos no soportados retornan una matriz completamente vacía,
    // por lo que se representan visualmente como un espacio.
    always_comb begin

        case (ascii_i)

            // Space
            8'h20: pattern = {
                8'b00000000,
